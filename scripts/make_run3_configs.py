"""Write the run 3 configs (docs/run3.md) from one definition, so they cannot drift apart.

    python scripts/make_run3_configs.py          # writes configs/run3/*.yaml
    python scripts/make_run3_configs.py --check  # fails if the committed files differ

The committed YAML files are what runs; this script only generates them.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODELS = {"qwen": ("Qwen/Qwen2.5-7B-Instruct", [8, 13, 20]), "gemma": ("google/gemma-2-9b-it", [12, 20, 28])}
# Too few validation scenarios (3-5) for the scenario-group bootstrap: described, not dose-tested.
SCAN = ["age", "religion", "nationality", "appearance", "disability", "socioeconomic"]
# At least 8 validation scenarios. Race is the new category, gender the comparison with run 2.
DOSE = ["race", "gender"]
STRENGTHS = [-0.6, -0.3, -0.15, -0.1, 0.0, 0.1, 0.15, 0.3, 0.6]


def config(model, axis, kind):
    model_id, layers = MODELS[model]
    if kind == "scan":
        head = (f"# Run 3 bias scan (docs/run3.md): {axis}, {model}. Unsteered and prompt baselines only,\n"
                "# BF16, validation. No vector is extracted or applied. Generated by scripts/make_run3_configs.py.\n")
        steering = ("  layers: []\n  method: mean_difference\n  positions: last\n  strengths: [0.0]\n  sources: []\n")
    else:
        head = (f"# Run 3 dose test (docs/run3.md): {axis}, {model}. BF16, validation only; never evaluate test here.\n"
                "# Stereotype contrast, same layers, strengths and pass rule as run 2.\n"
                "# Generated by scripts/make_run3_configs.py.\n")
        steering = (f"  layers: {layers}\n  method: mean_difference\n  positions: last\n"
                    f"  strengths: {STRENGTHS}\n  sources: [reference, random]\n  contrast: stereotype\n")
    return (head + "seed: 42\nmodel:\n"
            f"  id: {model_id}\n  revision: main\n  device: cuda:0\n  compute_dtype: bfloat16\n  attention: eager\n"
            "precisions: [bf16]\ndata:\n"
            f"  prepared: data/prepared/{axis}\n  train_limit: 128\n  validation_limit: null\n  test_limit: null\n"
            "steering:\n" + steering +
            "evaluation:\n  max_new_tokens: 12\n  fairness_prompt: false\n  include_prompt_baseline: true\n"
            f"output:\n  root: artifacts/run3/{kind}-{model}-{axis}\n")


def files():
    result = {}
    for model in MODELS:
        for axis in SCAN:
            result[f"scan_{model}_{axis}.yaml"] = config(model, axis, "scan")
        for axis in DOSE:
            result[f"dose_{model}_{axis}.yaml"] = config(model, axis, "dose")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    folder = ROOT / "configs" / "run3"
    wanted = files()
    if args.check:
        stale = [name for name, text in wanted.items() if not (folder / name).is_file()
                 or (folder / name).read_text(encoding="utf-8") != text]
        extra = sorted(p.name for p in folder.glob("*.yaml") if p.name not in wanted) if folder.exists() else []
        if stale or extra:
            print(f"Out of date: {stale}; unexpected: {extra}", file=sys.stderr)
            return 1
        return 0
    folder.mkdir(parents=True, exist_ok=True)
    for name, text in wanted.items():
        (folder / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {len(wanted)} configs to {folder}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
